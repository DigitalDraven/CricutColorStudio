test("version strings agree across index.html, app.js and README", () => {
  const html = fs.readFileSync(path.join(root, "index.html"), "utf8"), js = fs.readFileSync(path.join(root, "js", "app.js"), "utf8"), md = fs.readFileSync(path.join(root, "README.md"), "utf8");
  const v = (html.match(/<title>Cricut Color Studio v([\d.]+)<\/title>/) || [])[1]; ok(v, "no version in <title>");
  ok(js.startsWith("/* Cricut Color Studio v" + v + " "), "app.js header version differs from " + v);
  ok(html.includes("css/styles.css?v=" + v) && html.includes("js/app.js?v=" + v), "cache-busting ?v= differs from " + v);
  ok(new RegExp("\\*\\*Version:\\*\\* " + v.replace(/\./g, "\\.")).test(md), "README **Version:** differs from " + v);
  const stray = [...js.matchAll(/(?:generated by Cricut Color Studio |STUDIO — V)([\d.]+)/g)].filter(m => m[1].replace(/\.$/, "") !== v);
  ok(!stray.length, "stale version string in app.js: " + (stray[0] && stray[0][1]));
});

test("palette is identical across noisy variants of the same image", () => {
  const seen = new Set();
  for (let s = 1; s <= 8; s++) seen.add(L.quantize(cartoon(200, 200, s, true), 4, true).colors.map(c => c.join(",")).sort().join("|"));
  ok(seen.size === 1, seen.size + " different palettes");
});

test("accent color survives quantizing (4 real colors, no blends)", () => {
  const q = L.quantize(cartoon(200, 200, 1, true), 4, true);
  ok(q.colors.length === 4, "got " + q.colors.length + " colors");
  ok(q.colors.some(c => Math.abs(c[0] - 231) < 8 && Math.abs(c[1] - 131) < 8 && Math.abs(c[2] - 40) < 8), "orange accent missing");
});

test("Simplify leaves no transparent specks and does not add pieces", () => {
  const W = 200, H = 200, q0 = L.quantize(cartoon(W, H, 3, true), 4, true), mm = 152.4 / W, lv = L.SIMPLIFY_LEVELS.medium;
  const off = new Uint8Array(L.smoothColorLabels(q0.pixels, W, H, 1)), on = new Uint8Array(off), minArea = lv.mm2 / (mm * mm);
  L.simplifyLabelsForCutting(on, W, H, q0.colors.length, mm, minArea, lv.thickness);
  const count = p => L.findComponents(p, W, H, 8).reduce((n, cs) => n + cs.filter(c => c.length >= minArea).length, 0);
  ok(enclosedGaps(on, W, H, minArea) === 0, "specks remain after Simplify");
  ok(count(on) <= count(off), "Simplify increased the number of pieces");
});

test("tiny pieces are recolored, never deleted (reassignToNeighbor / absorb)", () => {
  const W = 30, H = 30, p = new Uint8Array(W * H).fill(0);
  for (let y = 10; y < 12; y++) for (let x = 10; x < 12; x++) p[y * W + x] = 1;   // 4-pixel island of color 1
  const r = L.absorbSmallComponents(p, W, H, 2, 12);
  ok(r.pieces === 1 && r.recolored === 4, "island not absorbed");
  ok(!p.includes(255) && !p.includes(1), "pixels were deleted or left behind");
});

test("smoothing cannot split a piece in two (thin bridge is protected)", () => {
  const W = 60, H = 30, before = new Uint8Array(W * H).fill(1);
  for (let y = 8; y < 22; y++) { for (let x = 4; x < 24; x++) before[y * W + x] = 0; for (let x = 36; x < 56; x++) before[y * W + x] = 0; }
  for (let y = 14; y < 16; y++) for (let x = 24; x < 36; x++) before[y * W + x] = 0;   // 2px bridge joins two blobs
  ok(L.findComponents(before, W, H, 2)[0].length === 1, "test setup: blobs should start connected");
  const after = L.majorityFilter(before, W, H, 2, 2);
  ok(L.findComponents(after, W, H, 2)[0].length >= 2, "test setup: filter should break the bridge");
  const n = L.protectSplitPieces(before, after, W, H, 2, 12);
  ok(n >= 1, "nothing protected");
  ok(L.findComponents(after, W, H, 2)[0].length === 1, "bridge still broken after protection");
});

test("layer overlap grows a lighter layer under a darker one only", () => {
  const W = 20, H = 10, p = new Uint8Array(W * H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) p[y * W + x] = x < 10 ? 0 : 1;   // 0 = light, 1 = dark
  const lum = [200, 20], light = [[]], dark = [[]];
  for (let i = 0; i < p.length; i++) (p[i] === 0 ? light[0] : dark[0]).push(i);
  const grownLight = L.overlapMask(p, W, H, light, lum, 0, 2), grownDark = L.overlapMask(p, W, H, dark, lum, 1, 2);
  const count = m => m.reduce((n, v) => n + (v === 0), 0);
  ok(count(grownLight) === light[0].length + 2 * H, "light layer should grow 2px into dark: " + count(grownLight));
  ok(count(grownDark) === dark[0].length, "dark layer must not grow into lighter colors");
});

