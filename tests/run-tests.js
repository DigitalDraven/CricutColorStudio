// Run with:  node tests/run-tests.js   (or: npm test).  No dependencies.
const fs = require("fs"), path = require("path");
const L = require("./load-app.js");
let failed = 0, passed = 0;
function test(name, fn) { try { fn(); passed++; console.log("  PASS  " + name); } catch (e) { failed++; console.log("  FAIL  " + name + "\n        " + e.message); } }
function ok(c, msg) { if (!c) throw new Error(msg); }
const root = path.join(__dirname, "..");

// ---- helpers ----
function rng(seed) { let r = seed >>> 0; return () => (r = (r * 1664525 + 1013904223) >>> 0) / 4294967296; }
function cartoon(W, H, seed, noise) {            // cyan bg, peach disc, black bar, orange accents, shaded ramp
  const rnd = rng(seed), d = new Uint8ClampedArray(W * H * 4);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    let c = [0, 200, 220]; const dx = x - W / 2, dy = y - H / 2;
    if (dx * dx + dy * dy < (W * .27) ** 2) c = [247, 207, 171];
    if (Math.abs(dx) < W * .2 && dy > -H * .07 && dy < 0) c = [0, 0, 0];
    if (x > W * .67 && x < W * .8 && y > H * .13 && y < H * .27) c = [231, 131, 40];
    const n = noise ? ((rnd() * 5 - 2.5) | 0) : 0, i = (y * W + x) * 4;
    d[i] = c[0] + n; d[i + 1] = c[1] + n; d[i + 2] = c[2] + n; d[i + 3] = 255;
  }
  return d;
}
function enclosedGaps(pixels, W, H, minArea) {   // transparent pockets created by deleting pieces under minArea
  const f = new Uint8Array(pixels), comps = L.findComponents(pixels, W, H, 16);
  comps.forEach(cs => cs.forEach(c => { if (c.length < minArea) c.forEach(id => f[id] = 255); }));
  const tr = L.findComponents(new Uint8Array(f.map(v => v === 255 ? 0 : 1)), W, H, 2)[0]; let n = 0;
  for (const c of tr) { let edge = false; for (const id of c) { const x = id % W, y = (id / W) | 0; if (!x || !y || x === W - 1 || y === H - 1) { edge = true; break; } } if (!edge) n++; }
  return n;
}

